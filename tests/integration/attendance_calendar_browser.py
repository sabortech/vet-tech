"""Run against the isolated attendance preview only; no real patient data."""
import argparse
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--url', default='http://localhost:3027')
parser.add_argument('--chromium', required=True)
parser.add_argument('--output', type=Path, required=True)
args = parser.parse_args()
args.output.mkdir(parents=True, exist_ok=True)
with sync_playwright() as p:
    browser = p.chromium.launch(executable_path=args.chromium, args=['--no-sandbox'])
    page = browser.new_page(viewport={'width': 1440, 'height': 1000})
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto(args.url)
    page.get_by_role('heading', name='Jessy', exact=True).wait_for()
    clinical_date = page.get_by_role('button', name='Data do atendimento', exact=True)
    clinical_return = page.get_by_role('button', name='Retorno (opcional)', exact=True)
    clinical_date.locator('svg').click()
    dialog = page.get_by_role('dialog')
    expect(dialog).to_be_visible()
    expect(dialog.get_by_role('combobox', name='Mês do calendário')).to_have_text('Novembro')
    dialog.get_by_role('button', name='Mês anterior', exact=True).click()
    expect(dialog.get_by_role('combobox', name='Mês do calendário')).to_have_text('Outubro')
    page.keyboard.press('Escape')
    expect(dialog).to_be_hidden()
    expect(clinical_date).to_have_text('02/11/2026')
    expect(clinical_date).to_be_focused()
    expect(page.get_by_text('Última versão confirmada', exact=True)).to_be_visible()
    clinical_return.click()
    dialog.get_by_role('combobox', name='Mês do calendário').click()
    page.get_by_role('option', name='Fevereiro', exact=True).click()
    dialog.get_by_role('combobox', name='Ano do calendário').click()
    page.get_by_role('option', name='2028', exact=True).click()
    expect(dialog.get_by_role('button', name='2028-02-29', exact=True)).to_be_visible()
    led = dialog.locator('.vet-date-led-track')
    start = led.evaluate('(e)=>getComputedStyle(e).strokeDashoffset')
    page.wait_for_timeout(200)
    end = led.evaluate('(e)=>getComputedStyle(e).strokeDashoffset')
    assert start != end, (start, end)
    assert led.evaluate('(e)=>getComputedStyle(e).animationName') == 'vet-date-border-orbit'
    page.screenshot(animations='disabled', path=str(args.output/'desktop.png'))
    dialog.get_by_role('button', name='2028-02-29', exact=True).click()
    expect(dialog).to_be_hidden()
    expect(clinical_return).to_have_text('29/02/2028')
    expect(clinical_date).to_have_text('02/11/2026')
    expect(clinical_return).to_be_focused()
    expect(page.get_by_text('Há alterações não salvas', exact=True)).to_be_visible()
    clinical_return.click()
    dialog.get_by_role('button', name='Limpar data', exact=True).click()
    expect(clinical_return).to_have_text('Selecionar data')
    for card in page.locator('.attendance-record-card').all():
        card.get_by_role('button', name='Adicionar', exact=True).click()
    expect(page.locator('.attendance-date-trigger')).to_have_count(9)
    for field in page.locator('.attendance-record-card .attendance-date-trigger').all():
        field.click()
        day = dialog.locator('.vet-date-day:not(:disabled)').first
        iso = day.get_attribute('aria-label')
        day.click()
        expect(dialog).to_be_hidden()
        expect(field).to_have_text('/'.join(reversed(iso.split('-'))))
        expect(field).to_be_focused()
    page.set_viewport_size({'width': 390, 'height': 844})
    clinical_return.click()
    expect(dialog).to_be_visible()
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    assert dialog.evaluate('(e)=>e.scrollWidth <= e.clientWidth')
    page.screenshot(animations='disabled', path=str(args.output/'mobile.png'))
    dialog.get_by_role('combobox', name='Mês do calendário').click()
    page.screenshot(animations='disabled', path=str(args.output/'mobile-month.png'))
    page.keyboard.press('Escape')
    expect(dialog).to_be_visible()
    page.emulate_media(reduced_motion='reduce')
    assert led.evaluate('(e)=>getComputedStyle(e).animationDuration') == '12s'
    page.evaluate("window.dispatchEvent(new StorageEvent('storage',{key:'vet_tech_theme',newValue:'dark'}))")
    assert dialog.evaluate('(e)=>getComputedStyle(e).color') == 'rgb(238, 243, 239)'
    page.screenshot(animations='disabled', path=str(args.output/'mobile-dark.png'))
    dialog.get_by_role('button', name='Fechar calendário', exact=True).click()
    expect(dialog).to_be_hidden()
    page.set_viewport_size({'width': 1440, 'height': 1000})
    page.goto(args.url+'/agenda')
    page.get_by_role('button', name='Escolher data', exact=True).click()
    expect(page.get_by_role('heading', name='Um dia de cada vez', exact=True)).to_be_visible()
    page.get_by_role('button', name='Próximo mês', exact=True).click()
    expect(page.get_by_role('dialog').locator('.vet-date-led-track')).to_be_visible()
    page.screenshot(animations='disabled', path=str(args.output/'agenda-regression.png'))
    page.get_by_role('button', name='Voltar à agenda', exact=True).click()
    expect(page.get_by_role('dialog')).to_be_hidden()
    assert not errors, errors
    browser.close()
(args.output/'results.md').write_text('Prévia sintética: abertura pelo campo e ícone, cancelamento sem edição, mês/ano, 29/02/2028, seleção e limpeza do retorno, sete campos de datas dos quatro grupos, foco restaurado, LED SVG em movimento, desaceleração em movimento reduzido, desktop 1440px e mobile 390px sem overflow, tema escuro e regressão visual do calendário da agenda. Nenhuma exceção JavaScript; backend remoto não exercitado.\n')
print('PASS: calendário clínico, todos os campos, mês/ano, foco, LED, mobile e agenda')
