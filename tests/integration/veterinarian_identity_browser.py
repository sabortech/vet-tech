"""Use veterinarian_identity_preview only. All account data is synthetic."""
import argparse
import re
from pathlib import Path
from playwright.sync_api import sync_playwright,expect
parser=argparse.ArgumentParser()
parser.add_argument('--url',default='http://localhost:3038')
parser.add_argument('--chromium',required=True)
parser.add_argument('--output',type=Path,required=True)
a=parser.parse_args();a.output.mkdir(parents=True,exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path=a.chromium,args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1440,'height':1000})
    page.add_init_script("localStorage.setItem('vet_tech_theme','light')")
    errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(a.url)
    card=page.locator('.vet-schedule-identity')
    expect(card).to_contain_text('CRMV 12345 / SP')
    expect(card.get_by_text('Veterinário(a)',exact=True)).to_be_visible()
    expect(card.get_by_text('Dra. Fernanda Diniz',exact=True)).to_be_visible()
    expect(card.get_by_role('button',name='Sair',exact=True)).to_be_visible()
    expect(page.locator('.sidebar-navigation')).to_contain_text('Configurações')
    def no_overflow():
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
        card.screenshot(path=str(a.output/'current-card.png'))
        assert card.evaluate('(e)=>e.scrollWidth<=e.clientWidth+2'), card.evaluate('(e)=>({width:e.clientWidth,scroll:e.scrollWidth,children:[...e.querySelectorAll("*")].filter(c=>c.getBoundingClientRect().right>e.getBoundingClientRect().right).map(c=>({class:c.className,text:c.textContent}))})')
    no_overflow();card.screenshot(path=str(a.output/'card-light.png'))
    page.evaluate("window.dispatchEvent(new StorageEvent('storage',{key:'vet_tech_theme',newValue:'dark'}))")
    card.screenshot(path=str(a.output/'card-dark.png'))
    page.goto(a.url+'/?scenario=missing')
    expect(card).to_contain_text('CRMV não informado')
    expect(card).not_to_contain_text('12345')
    page.goto(a.url+'/?scenario=failure')
    expect(card).to_contain_text('Registro indisponível')
    card.get_by_role('button',name='Tentar novamente',exact=True).click()
    expect(card).to_contain_text('CRMV 12345 / SP')
    page.goto(a.url+'/?scenario=long')
    expect(card).to_contain_text('CRMV 12345 / SP')
    expect(card).to_contain_text('Dra. Fernanda Albuquerque de Vasconcelos Diniz')
    no_overflow();card.screenshot(path=str(a.output/'card-long-name.png'))
    page.get_by_role('button',name='Recolher menu',exact=True).click()
    expect(page.locator('.sidebar')).to_have_class(re.compile(r'\bsidebar--collapsed\b'))
    expect(card.locator('.vet-profile-registration')).to_be_hidden()
    expect(card.locator('.vet-profile-avatar')).to_be_visible()
    expect(card.get_by_role('button',name='Sair',exact=True)).to_be_visible()
    no_overflow();card.screenshot(path=str(a.output/'card-collapsed.png'))
    page.set_viewport_size({'width':390,'height':844})
    page.get_by_role('button',name='Abrir menu',exact=True).filter(visible=True).click()
    expect(page.locator('.sidebar')).to_have_class(re.compile(r'\bsidebar--mobile-open\b'))
    expect(card.locator('.vet-profile-registration')).to_be_visible()
    expect(card.get_by_text('Veterinário(a)',exact=True)).to_be_visible()
    no_overflow();page.screenshot(path=str(a.output/'mobile.png'))
    assert not errors,errors
    browser.close()
print('OK: card profissional, CRMV/UF, ausência/falha/retry, nome longo, temas, compacto e drawer móvel.')
