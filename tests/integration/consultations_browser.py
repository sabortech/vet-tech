"""Run against an isolated synthetic preview; never use with live patient data."""
import argparse
from pathlib import Path
from playwright.sync_api import sync_playwright,expect
parser=argparse.ArgumentParser()
parser.add_argument('--url',default='http://localhost:3037')
parser.add_argument('--chromium',required=True)
parser.add_argument('--output',type=Path,required=True)
args=parser.parse_args()
out=args.output;out.mkdir(parents=True,exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path=args.chromium,args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1440,'height':1000})
    errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(args.url+'/?secao=consultas')
    expect(page.locator('.consultations-card')).to_have_count(5)
    page.locator('.consultations-patient-button').first.click()
    expect(page.locator('.consultations-summary')).to_contain_text('Alergia alimentar · controlada')
    expect(page.locator('.consultations-baby-turtle')).to_be_visible()
    page.screenshot(path=str(out/'desktop.png'))
    page.locator('.consultations-patient-button').nth(1).click()
    expect(page.locator('.consultations-summary')).to_contain_text('Alergias não informadas')
    expect(page.locator('.consultations-summary')).not_to_contain_text('Alergia alimentar')
    page.get_by_role('textbox',name='Buscar por nome do pet').fill('Max')
    expect(page.locator('.consultations-card')).to_have_count(1)
    page.get_by_role('button',name='Canceladas',exact=True).click()
    expect(page.locator('.consultations-card')).to_have_count(1)
    expect(page.locator('.consultations-card .consultations-status')).to_have_text('Cancelada')
    expect(page.locator('.consultations-start')).to_have_count(0)
    expect(page.locator('.consultations-filter-icon')).to_be_visible()
    assert float(page.locator('.consultations-search').evaluate('(e)=>getComputedStyle(e).borderTopLeftRadius').replace('px','')) >= 20
    page.screenshot(path=str(out/'cancelled-desktop.png'))
    page.get_by_role('button',name='Concluídas',exact=True).click()
    expect(page.get_by_text('Nenhuma consulta encontrada',exact=True)).to_be_visible()
    page.get_by_role('textbox',name='Buscar por nome do pet').fill('')
    page.get_by_role('button',name='Pendentes',exact=True).click()
    expect(page.locator('.consultations-card')).to_have_count(5)
    page.locator('.consultations-patient-button').first.click()
    expect(page.locator('.consultations-summary')).to_contain_text('Alergia alimentar')
    page.evaluate("document.documentElement.setAttribute('data-vt-theme','dark')")
    page.screenshot(path=str(out/'dark.png'))
    page.set_viewport_size({'width':390,'height':844})
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    page.screenshot(path=str(out/'mobile-dark.png'),full_page=True)
    page.evaluate("document.documentElement.setAttribute('data-vt-theme','light')")
    page.screenshot(path=str(out/'mobile-light.png'),full_page=True)
    assert not errors,errors
    print('OK: seleção, alergias, busca arredondada, filtro com ícone, Canceladas sem início, temas e mobile sem overflow.')
    browser.close()
