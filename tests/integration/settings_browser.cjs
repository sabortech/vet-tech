/* Chromium integration; credentials read only from ignored synthetic fixtures.
   Usage: NODE_PATH=/path/to/node_modules node tests/integration/settings_browser.cjs */
const {chromium}=require('playwright');
const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'../..');
const fixturePath=path.join(root,'.env.settings-fixtures.json');
const fixture=JSON.parse(fs.readFileSync(fixturePath));
if(fixture.environment!=='development'||fixture.synthetic!==true)throw Error('Requires synthetic development fixtures');
const evidence=path.join(root,'openspec/changes/archive/2026-10-25-adicionar-configuracoes-tutor/evidence');
const origin=process.env.VETTECH_TEST_URL||'http://127.0.0.1:3000';
const executablePath=process.env.VETTECH_CHROMIUM_PATH;
const assert=(v,msg)=>{if(!v)throw Error(msg);};
const delay=ms=>new Promise(resolve=>setTimeout(resolve,ms));
(async()=>{
 const browser=await chromium.launch({headless:true,...(executablePath?{executablePath}:{}),args:['--no-sandbox']});
 try {
 const context=await browser.newContext({viewport:{width:1366,height:1000}});
 const page=await context.newPage();
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const actor=fixture.actors[1];
 await page.goto(origin+'/login',{waitUntil:'networkidle'});
 await page.locator('[name=email]').fill(actor.data.email);
 await page.locator('[name=password]').fill(actor.data.password);
 await page.getByRole('button',{name:'Login',exact:true}).click();
 await page.getByRole('heading',{name:'Perfil do tutor',exact:true}).waitFor({timeout:30000});
 await delay(7000); // Space authenticated catalog calls from account loading.
 await page.getByRole('link',{name:'Configurações',exact:true}).click();
 await page.waitForFunction(()=>document.getElementById('settings-nome')?.value.startsWith('Fixture'));
 const tab=async name=>{await page.getByRole('tab',{name,exact:true}).click();await page.waitForFunction(n=>document.querySelector('[role=tab][aria-selected=true]')?.textContent===n,name);};
 console.log('PASS account loaded');
 await page.locator('#settings-nome').fill('Fixture rascunho');
 await page.getByRole('button',{name:'Cancelar',exact:true}).click();
 await page.waitForFunction(()=>document.getElementById('settings-nome').value!=='Fixture rascunho');
 await page.locator('#settings-nome').fill('Fixture navegador '+Date.now());
 await page.getByRole('button',{name:'Salvar alterações',exact:true}).click();
 await page.getByText('Dados atualizados com sucesso.',{exact:true}).waitFor({timeout:30000});
 console.log('PASS save and cancel');
 await page.locator('#settings-nome').fill('Fixture alteração pendente');
 await page.getByRole('tab',{name:'Preferências',exact:true}).click();
 await page.getByRole('alertdialog').waitFor();
 await page.getByRole('button',{name:'Continuar editando'}).click();
 await page.getByRole('alertdialog').waitFor({state:'hidden'});
 assert(await page.locator('#settings-nome').inputValue()==='Fixture alteração pendente','Draft lost');
 await page.getByRole('tab',{name:'Preferências',exact:true}).click();
 await page.getByRole('button',{name:'Descartar alterações'}).click();
 await page.locator('#theme-switch').waitFor();
 console.log('PASS discard guard');
 await page.locator('#theme-switch').check();
 await page.waitForFunction(()=>document.documentElement.dataset.vtTheme==='dark');
 assert(await page.locator('.sidebar').evaluate(e=>getComputedStyle(e).backgroundColor)==='rgb(24, 58, 42)','Sidebar theme');
 const other=await context.newPage();await other.goto(origin+'/login',{waitUntil:'networkidle'});
 assert(await other.evaluate(()=>document.documentElement.dataset.vtTheme)==='dark','Stored theme');
 await page.locator('#theme-switch').uncheck();await other.waitForFunction(()=>document.documentElement.dataset.vtTheme==='light');
 await page.locator('#theme-switch').check();await other.waitForFunction(()=>document.documentElement.dataset.vtTheme==='dark');
 await other.close();
 const expanded=page.locator('#sidebar-switch');
 await expanded.click();await page.locator('.sidebar--collapsed').waitFor();
 await page.getByRole('button',{name:'Abrir menu',exact:true}).click();
 await page.waitForFunction(()=>document.getElementById('sidebar-switch')?.checked===true);
 console.log('PASS theme storage, tabs and sidebar');
 await tab('Minha conta');
 for(const theme of ['light','dark']){
  await tab('Preferências');
  if(theme==='dark')await page.locator('#theme-switch').check();else await page.locator('#theme-switch').uncheck();
  await tab('Minha conta');
  for(const width of [1366,1920,768,390]){
   await page.setViewportSize({width,height:1000});await delay(350);
   assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Horizontal overflow '+width);
   await page.screenshot({path:path.join(evidence,`settings-${theme}-${width}.png`),fullPage:true});
  }
 }
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Abrir menu',exact:true}).click();
 await page.locator('.sidebar--mobile-open').waitFor();
 await page.keyboard.press('Escape');
 await page.locator('.sidebar--mobile-open').waitFor({state:'hidden'});
 await page.setViewportSize({width:1366,height:1000});
 console.log('PASS responsive themes and mobile drawer');
 await tab('Segurança');
 await page.screenshot({path:path.join(evidence,'security-dark-1366.png'),fullPage:true});
 await page.locator('#current_password').fill('incorrect-synthetic');
 await page.locator('#new_password').fill('temporary');
 await page.locator('#password_confirmation').fill('different');
 await page.getByRole('button',{name:'Atualizar senha'}).click();
 await page.getByText('As senhas não coincidem.',{exact:true}).waitFor();
 await page.locator('#password_confirmation').fill('temporary');
 await page.getByRole('button',{name:'Atualizar senha'}).click();
 await page.getByText('Senha atual incorreta.',{exact:true}).waitFor({timeout:30000});
 await delay(4000);
 const newPassword=require('crypto').randomBytes(18).toString('base64url');
 await page.locator('#current_password').fill(actor.data.password);
 await page.locator('#new_password').fill(newPassword);
 await page.locator('#password_confirmation').fill(newPassword);
 await page.getByRole('button',{name:'Atualizar senha'}).click();
 await page.getByText('Senha atualizada. Entre novamente com sua nova senha.',{exact:true}).waitFor({timeout:30000});
 actor.data.password=newPassword;fs.writeFileSync(fixturePath,JSON.stringify(fixture));
 assert(await page.evaluate(()=>document.documentElement.dataset.vtTheme)==='dark','Logout theme');
 await page.screenshot({path:path.join(evidence,'login-dark-1366.png'),fullPage:true});
 await delay(4000);
 await page.locator('[name=email]').fill(actor.data.email);
 await page.locator('[name=password]').fill(newPassword);
 await page.getByRole('button',{name:'Login',exact:true}).click();
 await page.getByRole('heading',{name:'Perfil do tutor',exact:true}).waitFor({timeout:30000});
 await page.screenshot({path:path.join(evidence,'pets-dark-1366.png'),fullPage:true});
 console.log('PASS password validation, logout and new login');
 await page.getByRole('button',{name:'Sair',exact:true}).click();
 await page.getByRole('button',{name:'Cadastre-se!'}).click();
 await page.waitForURL(/\/cadastro\/?$/);
 await page.screenshot({path:path.join(evidence,'signup-dark-1366.png'),fullPage:true});
 assert(await page.evaluate(()=>document.documentElement.dataset.vtTheme)==='dark','Signup theme');
 const reload=await context.newPage();await reload.goto(origin+'/configuracoes',{waitUntil:'networkidle'});await reload.waitForURL(/\/login\/?$/);
 console.log('PASS direct settings access without session');
 assert(errors.length===0,'Browser errors: '+errors.join(';'));
 const fallback=await browser.newContext();
 await fallback.addInitScript(() => Object.defineProperty(window,'localStorage',{configurable:true,get(){throw new DOMException('Blocked','SecurityError');}}));
 const fallbackPage=await fallback.newPage();const fallbackErrors=[];fallbackPage.on('pageerror',e=>fallbackErrors.push(e.message));
 await fallbackPage.goto(origin+'/login',{waitUntil:'networkidle'});
 await fallbackPage.getByRole('button',{name:'Login',exact:true}).waitFor();
 assert(await fallbackPage.evaluate(()=>document.documentElement.dataset.vtTheme)==='light','Fallback theme');
 assert(fallbackErrors.length===0,'Storage unavailable broke interface');
 await fallback.close();
 console.log('PASS blocked storage fallback');
 const firstPaint=await browser.newContext();
 await firstPaint.addInitScript(()=>{localStorage.setItem('vet_tech_theme','dark');window.vtFirstTheme=null;new MutationObserver(()=>{if(window.vtFirstTheme===null&&document.querySelector('input[name=email]'))window.vtFirstTheme=document.documentElement.dataset.vtTheme;}).observe(document,{childList:true,subtree:true});});
 const firstPage=await firstPaint.newPage();await firstPage.goto(origin+'/login',{waitUntil:'networkidle'});
 assert(await firstPage.evaluate(()=>window.vtFirstTheme)==='dark','Theme applied after public content');
 await firstPaint.close();
 console.log('PASS dark theme before first public form');
 console.log('PASS complete settings browser integration');
 }finally{await browser.close();}
})().catch(e=>{console.error(e.message);process.exitCode=1;});
