"""Shared history and command rounding, using attendance_completion_preview only."""
import argparse
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--url',default='http://localhost:3027')
parser.add_argument('--chromium',required=True)
parser.add_argument('--output',type=Path,required=True)
args=parser.parse_args()
args.output.mkdir(parents=True,exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path=args.chromium,args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1440,'height':1000})
    errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(args.url+'/atendimento/43')
    page.get_by_role('heading',name='Jessy',exact=True).wait_for()
    page.locator('#clinic-diagnostico').fill('Rascunho que deve permanecer')
    page.get_by_role('button',name='Consultar histórico anterior',exact=True).click()
    dialog=page.locator('.attendance-history-dialog')
    expect(dialog.get_by_text('Avaliação anterior de Jessy',exact=True)).to_be_visible()
    dialog.get_by_role('button',name='Fechar histórico',exact=True).click()
    expect(page.locator('#clinic-diagnostico')).to_have_value('Rascunho que deve permanecer')
    page.goto(args.url+'/?secao=horarios')
    first=page.locator('[data-appointment-id="43"]').get_by_role('button',name='Histórico',exact=True)
    first.click()
    expect(dialog.get_by_role('heading',name='Histórico anterior',exact=True)).to_be_visible()
    expect(dialog.get_by_text('Avaliação anterior de Jessy',exact=True)).to_be_visible()
    expect(page.get_by_text('Histórico publicado do pet',exact=True)).to_have_count(0)
    page.screenshot(path=str(args.output/'card-history-light.png'),animations='disabled')
    dialog.get_by_role('button',name='Voltar à agenda',exact=True).click()
    expect(first).to_be_focused()
    second=page.locator('[data-appointment-id="44"]').get_by_role('button',name='Histórico',exact=True)
    second.click()
    expect(dialog.get_by_role('alert')).to_have_text('Falha sintética ao consultar o pet do card')
    dialog.get_by_role('button',name='Tentar novamente',exact=True).click()
    expect(dialog.get_by_text('Avaliação anterior de Nina',exact=True)).to_be_visible()
    expect(dialog.get_by_text('Avaliação anterior de Jessy',exact=True)).to_have_count(0)
    page.evaluate("window.dispatchEvent(new StorageEvent('storage',{key:'vet_tech_theme',newValue:'dark'}))")
    expect(dialog).to_have_css('color','rgb(238, 243, 239)')
    page.screenshot(path=str(args.output/'card-history-dark.png'),animations='disabled')
    page.set_viewport_size({'width':390,'height':844})
    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
    page.screenshot(path=str(args.output/'card-history-mobile.png'),animations='disabled')
    page.keyboard.press('Escape')
    expect(dialog).to_be_hidden()
    expect(second).to_be_focused()
    page.goto(args.url+'/?secao=consultas')
    page.locator('[data-consultation-id="44"]').get_by_role('button',name='Ver prontuário',exact=True).click()
    expect(dialog.get_by_text('Avaliação anterior de Nina',exact=True)).to_be_visible()
    dialog.get_by_role('button',name='Voltar às consultas',exact=True).click()
    def rounded():
        bad=page.evaluate('''()=>Array.from(document.querySelectorAll('button,input[type=submit],input[type=button],a.rt-Button,[role=button]')).filter(e=>e.getClientRects().length && !e.matches('#vettech-mascote,[role=switch],[role=checkbox],[role=radio]')).filter(e=>['borderTopLeftRadius','borderTopRightRadius','borderBottomLeftRadius','borderBottomRightRadius'].some(k=>parseFloat(getComputedStyle(e)[k])===0)).map(e=>({text:e.textContent,classes:e.className}))''')
        assert not bad,bad
    rounded()
    for route in ['/login','/cadastro']:
        page.goto('http://localhost:3000'+route)
        page.get_by_role('button').first.wait_for()
        rounded()
    assert not errors,errors
    browser.close()
(args.output/'results.md').write_text('Prévia sintética: histórico no atendimento, Horários e Consultas abre o mesmo modal; pet correto por card, erro/nova tentativa mantém alvo distinto da consulta anterior; fechar pelo botão/Escape restaura foco; sem histórico inline; rascunho preservado; temas claro/escuro e mobile 390px sem overflow. Botões visíveis em Consultas, login e cadastro com quatro cantos arredondados. Nenhuma exceção JavaScript; backend remoto não exercitado.\n')
print('PASS: modal compartilhado, pet correto/retry/foco, temas/mobile e botões globais')
