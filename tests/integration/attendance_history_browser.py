import argparse
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
parser=argparse.ArgumentParser()
parser.add_argument('--url',default='http://localhost:3027')
parser.add_argument('--chromium',required=True)
parser.add_argument('--output',type=Path,required=True)
args=parser.parse_args()
out=args.output;out.mkdir(parents=True,exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path=args.chromium,args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1440,'height':1000})
    errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(args.url);page.get_by_role('heading',name='Jessy',exact=True).wait_for()
    page.locator('#clinic-diagnostico').fill('Rascunho preservado')
    trigger=page.get_by_role('button',name='Consultar histórico anterior')
    trigger.click(); dialog=page.get_by_role('dialog');expect(dialog).to_be_visible()
    expect(dialog.get_by_role('status')).to_be_visible()
    expect(dialog.get_by_text('Avaliação sintética anterior',exact=True)).to_have_count(8)
    assert dialog.locator('img').evaluate('(e)=>e.complete && e.naturalWidth>0')
    page.screenshot(path=str(out/'desktop.png'))
    page.keyboard.press('Escape');expect(dialog).to_be_hidden();expect(trigger).to_be_focused()
    expect(page.locator('#clinic-diagnostico')).to_have_value('Rascunho preservado')
    trigger.click();expect(dialog.get_by_role('alert')).to_have_text('Falha sintética ao consultar histórico')
    dialog.get_by_role('button',name='Tentar novamente').click();expect(dialog.get_by_text('Avaliação sintética anterior',exact=True)).to_have_count(8)
    page.set_viewport_size({'width':390,'height':844})
    assert dialog.evaluate('(e)=>e.scrollWidth<=e.clientWidth')
    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
    page.screenshot(path=str(out/'mobile.png'))
    body=dialog.locator('.attendance-history-body');assert body.evaluate('(e)=>e.scrollHeight>e.clientHeight')
    body.evaluate('(e)=>e.scrollTop=e.scrollHeight');expect(dialog.get_by_role('heading',name='Exames',exact=True)).to_be_in_viewport()
    dialog.get_by_role('button',name='Fechar histórico',exact=True).click();expect(dialog).to_be_hidden()
    trigger.click();expect(dialog.get_by_text('Nenhum registro publicado nesta categoria.',exact=True)).to_have_count(5)
    page.screenshot(path=str(out/'empty.png'))
    dialog.get_by_role('button',name='Voltar ao atendimento').click();expect(dialog).to_be_hidden()
    assert not errors, errors
    browser.close()
(out/'results.md').write_text('Verificado com HTTP sintético: abertura imediata, loading, histórico com registros, erro e nova tentativa, cinco categorias vazias, Escape/X/botão, restauração de foco, rascunho preservado, tartaruga carregada, rolagem e ausência de overflow em 1440px e 390px. Nenhuma exceção JavaScript. Backend remoto não exercitado.\n')
print('PASS: modal, loading, dados, erro/retry, vazio, foco, rascunho e mobile')
