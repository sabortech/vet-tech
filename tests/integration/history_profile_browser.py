"""Use only with history_profile_preview synthetic app."""
import argparse
from pathlib import Path
from playwright.sync_api import sync_playwright,expect
parser=argparse.ArgumentParser()
parser.add_argument('--url',default='http://localhost:3038')
parser.add_argument('--chromium',required=True)
parser.add_argument('--output',type=Path,required=True)
a=parser.parse_args();a.output.mkdir(parents=True,exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path=a.chromium,args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1440,'height':1100})
    page.add_init_script("localStorage.setItem('vet_tech_theme','light')")
    errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(a.url)
    trigger=page.get_by_role('button',name='Consultar histórico anterior',exact=True)
    dialog=page.locator('.attendance-history-dialog')
    trigger.click()
    profile=dialog.locator('.history-profile')
    expect(profile.get_by_role('heading',name='Jessy',exact=True)).to_be_visible()
    expect(profile.locator('img')).to_be_visible()
    expect(profile.locator('.consultations-avatar-paw')).to_be_hidden()
    expect(profile).to_contain_text('31/01/2026')
    expect(profile).to_contain_text('Peso informado')
    expect(profile.locator('.history-profile-count')).to_have_text(['1','1','0','0','0'])
    expect(dialog.locator('.attendance-history-section')).to_have_count(5)
    dialog.screenshot(path=str(a.output/'light.png'))
    page.evaluate("window.dispatchEvent(new StorageEvent('storage',{key:'vet_tech_theme',newValue:'dark'}))")
    dialog.screenshot(path=str(a.output/'dark.png'))
    page.keyboard.press('Escape');expect(dialog).to_be_hidden();expect(trigger).to_be_focused()
    expect(page.locator('#clinic-diagnostico')).to_have_value('Rascunho preservado')
    page.set_viewport_size({'width':390,'height':844});trigger.click()
    expect(profile).to_be_visible()
    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
    assert dialog.evaluate('(e)=>e.scrollWidth<=e.clientWidth+2')
    dialog.screenshot(path=str(a.output/'mobile.png'))
    page.keyboard.press('Escape');expect(dialog).to_be_hidden()
    for scenario in ('no-photo','broken','empty','error'):
        page.goto(a.url+'/?scenario='+scenario)
        trigger.click()
        if scenario=='error':
            expect(dialog.get_by_role('alert')).to_contain_text('Falha sintética')
            expect(profile).to_have_count(0)
            dialog.get_by_role('button',name='Tentar novamente',exact=True).click()
        expect(profile).to_be_visible()
        if scenario in ('no-photo','broken'):expect(profile.locator('.consultations-avatar-paw')).to_be_visible()
        if scenario=='empty':expect(profile.locator('.history-profile-count')).to_have_text(['0','0','0','0','0'])
        page.keyboard.press('Escape');expect(dialog).to_be_hidden()
    assert not errors,errors
    browser.close()
print('OK: perfil no histórico, foto/fallback, contagens, temas/mobile, erro/retry/vazio, foco e rascunho.')
